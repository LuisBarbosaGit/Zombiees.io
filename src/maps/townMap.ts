export type StaticTile = 'wall' | 'tree' | 'floor';

export function tileAt(column: number, row: number): StaticTile {
  if (column < 0 || row < 0 || column >= MAP_WIDTH || row >= MAP_HEIGHT) return 'wall';
  const tile = EXTRACTED_COLLISION_ROWS[row][column];
  return tile === '#' ? 'wall' : tile === 'T' ? 'tree' : 'floor';
}

export function isStaticBlocked(column: number, row: number): boolean {
  return tileAt(column, row) !== 'floor';
}

export const WORLD_WIDTH = MAP_WIDTH * TILE_SIZE;
export const WORLD_HEIGHT = MAP_HEIGHT * TILE_SIZE;
